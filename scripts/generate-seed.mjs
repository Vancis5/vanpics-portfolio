import fs from 'fs';
import path from 'path';

// Helper to escape SQL single quotes
function escapeSql(str) {
  if (str === null || str === undefined) return 'NULL';
  return `'${String(str).replace(/'/g, "''")}'`;
}

async function main() {
  try {
    const photosPath = path.resolve('js/data/photos.js');
    const videosPath = path.resolve('js/data/videos.js');

    // On Windows, backslashes must be converted to forward slashes for file:// URLs
    const photosUrl = `file:///${photosPath.replace(/\\/g, '/')}`;
    const videosUrl = `file:///${videosPath.replace(/\\/g, '/')}`;

    console.log(`Importing photos from: ${photosUrl}`);
    console.log(`Importing videos from: ${videosUrl}`);

    // Dynamically import ESM files
    const { photos } = await import(photosUrl);
    const { videos } = await import(videosUrl);

    let sql = `-- ─────────────────────────────────────────────────────────────────────────────\n`;
    sql += `--  DATABASE SEED DATA — D1 SQLITE (AUTOGENERATED FROM STATIC JS DATA)\n`;
    sql += `-- ─────────────────────────────────────────────────────────────────────────────\n\n`;

    sql += `BEGIN TRANSACTION;\n\n`;
    sql += `DELETE FROM photos;\n`;
    sql += `DELETE FROM videos;\n\n`;

    // Process Photos
    sql += `-- Seed Photos\n`;
    for (const p of photos) {
      const srcKey = p.src;
      const baseFilename = srcKey.replace(/^photos\//, '');
      const thumbKey = `thumbs/${baseFilename}`;

      // Match raw image file in photos-raw/
      const baseNameWithoutExt = path.parse(baseFilename).name;
      const rawDir = path.resolve('photos-raw');
      let rawKey = null;
      if (fs.existsSync(rawDir)) {
        const rawFiles = fs.readdirSync(rawDir);
        const match = rawFiles.find(f => {
          return path.parse(f).name === baseNameWithoutExt && /\.(webp|jpg|jpeg|png)$/i.test(f);
        });
        if (match) {
          rawKey = `photos-raw/${match}`;
        }
      }

      const title = escapeSql(p.title);
      const src = escapeSql(srcKey);
      const thumb = escapeSql(thumbKey);
      const rawSrc = escapeSql(rawKey);
      const aspectRatio = p.aspectRatio || 1.0;
      const category = escapeSql(p.category || '');
      const location = escapeSql(p.location || null);
      const date = escapeSql(p.date || null);
      const desc = escapeSql(p.desc || null);
      const heroSlide = p.heroSlide ? 1 : 0;

      sql += `INSERT INTO photos (title, src, thumb, raw_src, aspect_ratio, category, location, date, desc, hero_slide)\n`;
      sql += `VALUES (${title}, ${src}, ${thumb}, ${rawSrc}, ${aspectRatio}, ${category}, ${location}, ${date}, ${desc}, ${heroSlide});\n`;
    }

    sql += `\n-- Seed Videos\n`;
    for (const v of videos) {
      const baseFilename = v.thumb.replace(/^photos\/thumbs\//, '').replace(/^photos\//, '');
      const posterKey = `posters/${baseFilename}`;

      const title = escapeSql(v.title);
      const src = escapeSql(v.src);
      const poster = escapeSql(posterKey);
      const aspectRatio = v.aspectRatio || 1.777;
      const location = escapeSql(v.location || null);
      const date = escapeSql(v.date || null);
      const desc = escapeSql(v.desc || null);
      const music = escapeSql(v.music || '');

      sql += `INSERT INTO videos (title, src, poster, aspect_ratio, location, date, desc, music)\n`;
      sql += `VALUES (${title}, ${src}, ${poster}, ${aspectRatio}, ${location}, ${date}, ${desc}, ${music});\n`;
    }

    sql += `\nCOMMIT;\n`;

    const outputPath = path.resolve('cms-worker/db/seed.sql');
    fs.writeFileSync(outputPath, sql, 'utf8');
    console.log(`\n✨ Success! Seed file generated at: ${outputPath}`);
  } catch (err) {
    console.error('❌ Error generating seed SQL:', err);
    process.exit(1);
  }
}

main();
