import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const DEFAULT_API_BASE = 'https://vanpics-cms-api.lorzanofrancisevan.workers.dev';
const DEFAULT_OUT_DIR = path.resolve('backfill-output/photos-lb');
const DEFAULT_SCRIPT_DIR = path.resolve('backfill-output');

export function parseCliArgs(args) {
  const options = {
    apiBase: DEFAULT_API_BASE,
    outDir: DEFAULT_OUT_DIR,
    scriptDir: DEFAULT_SCRIPT_DIR,
    concurrency: 4,
    limit: 100,
  };

  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === '--api' && args[i + 1]) {
      options.apiBase = args[++i].replace(/\/+$/, '');
    } else if (arg === '--out-dir' && args[i + 1]) {
      options.outDir = path.resolve(args[++i]);
    } else if (arg === '--script-dir' && args[i + 1]) {
      options.scriptDir = path.resolve(args[++i]);
    } else if (arg === '--concurrency' && args[i + 1]) {
      options.concurrency = Math.max(1, Number.parseInt(args[++i], 10) || 4);
    } else if (arg === '--limit' && args[i + 1]) {
      options.limit = Math.max(1, Number.parseInt(args[++i], 10) || 100);
    }
  }

  return options;
}

export async function fetchAllPhotos(apiBase, pageSize = 100) {
  const photos = [];
  let offset = 0;
  let hasMore = true;

  while (hasMore) {
    const url = `${apiBase}/api/photos?limit=${pageSize}&offset=${offset}`;
    const res = await fetch(url);
    if (!res.ok) {
      throw new Error(`Failed to fetch photos from ${url}: ${res.status} ${res.statusText}`);
    }

    const data = await res.json();
    const items = Array.isArray(data) ? data : data.items || [];
    if (items.length === 0) break;

    photos.push(...items);

    if (data.pagination && typeof data.pagination.nextOffset === 'number') {
      offset = data.pagination.nextOffset;
      if (offset >= (data.pagination.total || Infinity)) {
        hasMore = false;
      }
    } else if (items.length < pageSize) {
      hasMore = false;
    } else {
      offset += items.length;
    }
  }

  return photos;
}

export function resolvePhotoSources(photo) {
  const sourceUrl = photo.raw_src || photo.src;
  const isFromRaw = Boolean(photo.raw_src);

  let filename = '';
  try {
    const parsed = new URL(photo.src);
    filename = path.basename(parsed.pathname);
  } catch {
    filename = path.basename(photo.src || '');
  }

  const baseName = path.parse(filename).name || `photo-${photo.id}`;
  const outFilename = `${baseName}.webp`;
  const lbKey = `photos-lb/${outFilename}`;

  return {
    sourceUrl,
    isFromRaw,
    outFilename,
    lbKey,
  };
}

export async function processImageBuffer(inputBuffer) {
  return sharp(inputBuffer)
    .rotate()
    .resize({
      width: 1600,
      height: 1600,
      fit: 'inside',
      withoutEnlargement: true,
    })
    .webp({ quality: 80 })
    .toBuffer();
}

export function generateUploadScript(items, outDir) {
  let sh = `#!/usr/bin/env bash\n`;
  sh += `# Autogenerated R2 upload batch for 1600px lightbox tier\n`;
  sh += `set -euo pipefail\n\n`;
  sh += `echo "Uploading ${items.length} 1600px lightbox tier images to R2 (vanpics-media)..."\n\n`;

  for (const item of items) {
    const filePath = path.join(outDir, item.outFilename);
    sh += `npx wrangler r2 object put "vanpics-media/${item.lbKey}" --file="${filePath}" --content-type="image/webp" --remote\n`;
  }

  sh += `\necho "Finished uploading ${items.length} images to R2."\n`;
  return sh;
}

export function generateSqlScript(items) {
  let sql = `-- Autogenerated D1 update script for 1600px lightbox tier\n`;

  for (const item of items) {
    const escapedKey = item.lbKey.replace(/'/g, "''");
    sql += `UPDATE photos SET lb_src = '${escapedKey}' WHERE id = ${Number(item.id)};\n`;
  }

  return sql;
}

async function runPool(items, concurrency, fn) {
  const results = [];
  let index = 0;

  async function worker() {
    while (index < items.length) {
      const i = index++;
      // eslint-disable-next-line security/detect-object-injection
      const item = items[i];
      try {
        const res = await fn(item);
        results.push(res);
      } catch (err) {
        results.push({ item, error: err });
      }
    }
  }

  const workers = Array.from({ length: Math.min(concurrency, items.length) }, () => worker());
  await Promise.all(workers);
  return results;
}

export async function runBackfill(options = parseCliArgs(process.argv.slice(2))) {
  console.log(`[backfill] Connecting to CMS API: ${options.apiBase}`);
  const allPhotos = await fetchAllPhotos(options.apiBase, options.limit);
  console.log(`[backfill] Retrieved ${allPhotos.length} total photo records.`);

  const toProcess = allPhotos.filter(p => !p.lb_src);
  const skippedCount = allPhotos.length - toProcess.length;

  console.log(`[backfill] ${skippedCount} photos already have lb_src (skipped).`);
  console.log(`[backfill] ${toProcess.length} photos require 1600px generation.`);

  if (toProcess.length === 0) {
    console.log('[backfill] Nothing to process. All photos already have lb_src.');
    return { successCount: 0, skippedCount, failedCount: 0 };
  }

  if (!fs.existsSync(options.outDir)) {
    fs.mkdirSync(options.outDir, { recursive: true });
  }
  if (!fs.existsSync(options.scriptDir)) {
    fs.mkdirSync(options.scriptDir, { recursive: true });
  }

  console.log(`[backfill] Processing images with concurrency = ${options.concurrency}...`);
  let processedSoFar = 0;

  const results = await runPool(toProcess, options.concurrency, async (photo) => {
    const { sourceUrl, isFromRaw, outFilename, lbKey } = resolvePhotoSources(photo);
    const destPath = path.join(options.outDir, outFilename);

    const res = await fetch(sourceUrl);
    if (!res.ok) {
      throw new Error(`Failed to download ${sourceUrl}: ${res.status} ${res.statusText}`);
    }

    const inputBuffer = Buffer.from(await res.arrayBuffer());
    const outBuffer = await processImageBuffer(inputBuffer);
    fs.writeFileSync(destPath, outBuffer);

    processedSoFar++;
    if (processedSoFar % 10 === 0 || processedSoFar === toProcess.length) {
      console.log(`[backfill] Progress: ${processedSoFar}/${toProcess.length}`);
    }

    return {
      id: photo.id,
      title: photo.title,
      lbKey,
      outFilename,
      destPath,
      sourceUrl,
      isFromRaw,
    };
  });

  const successful = results.filter(r => !r.error);
  const failed = results.filter(r => r.error);

  console.log(`\n[backfill] Processing complete.`);
  console.log(`  - Successfully generated: ${successful.length}`);
  console.log(`  - Failed: ${failed.length}`);

  if (failed.length > 0) {
    console.warn('\n[backfill] Failures encountered:');
    for (const f of failed) {
      console.warn(`  - Photo id=${f.item?.id} (${f.item?.title}): ${f.error?.message}`);
    }
  }

  if (successful.length > 0) {
    const uploadShPath = path.join(options.scriptDir, 'upload-lb.sh');
    const updateSqlPath = path.join(options.scriptDir, 'update-lb.sql');

    fs.writeFileSync(uploadShPath, generateUploadScript(successful, options.outDir), { mode: 0o755 });
    fs.writeFileSync(updateSqlPath, generateSqlScript(successful));

    console.log(`\n[backfill] Generated reviewable artifacts:`);
    console.log(`  - Shell upload script: ${uploadShPath}`);
    console.log(`  - D1 update SQL:       ${updateSqlPath}`);
    console.log(`  - Local 1600px images: ${options.outDir} (${successful.length} files)`);
  }

  return {
    successCount: successful.length,
    skippedCount,
    failedCount: failed.length,
    successful,
  };
}

// Direct invocation check
const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);

if (isMain) {
  runBackfill().catch((err) => {
    console.error('[backfill] Fatal error:', err);
    process.exit(1);
  });
}
